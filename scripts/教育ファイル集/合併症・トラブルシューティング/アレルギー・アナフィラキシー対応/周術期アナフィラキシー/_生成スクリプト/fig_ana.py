def trim(name, pad=28):
    """下端の白余白を切り詰める（キャンバス高を余らせても図が間延びしない）"""
    from PIL import Image
    import numpy as np
    path = os.path.join(OUT, name)
    im = Image.open(path).convert("RGB")
    a = np.asarray(im)
    nonwhite = (a < 250).any(axis=2).any(axis=1)
    idx = np.nonzero(nonwhite)[0]
    if len(idx) == 0:
        return
    bottom = min(im.height, int(idx[-1]) + pad)
    if bottom < im.height:
        im.crop((0, 0, im.width, bottom)).save(path)


