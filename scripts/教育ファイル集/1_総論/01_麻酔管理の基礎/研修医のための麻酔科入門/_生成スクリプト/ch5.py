# ── 図：致死的トライアド ─────────────────────────
def figtriad():
    b = ""
    cx, cy, r, cr = 290, 152, 92, 58
    import math
    pts = []
    for i, (lab, sub) in enumerate([("低体温", "凝固酵素活性↓"), ("アシドーシス", "凝固因子機能↓"),
                                    ("凝固障害", "出血が止まらない")]):
        a = -math.pi / 2 + i * 2 * math.pi / 3
        x, y = cx + r * math.cos(a), cy + r * math.sin(a)
        pts.append((x, y))
        b += S.circle(x, y, cr, "red")
        b += S.t(x, y - 3, lab, 16, S.TXT["red"], "middle", bold=True)
        b += S.t(x, y + 17, sub, 12.5, S.INK, "middle")
    for i in range(3):
        x1, y1 = pts[i]
        x2, y2 = pts[(i + 1) % 3]
        dx, dy = x2 - x1, y2 - y1
        L = (dx * dx + dy * dy) ** .5
        b += S.arrow(x1 + dx / L * (cr + 4), y1 + dy / L * (cr + 4),
                     x2 - dx / L * (cr + 8), y2 - dy / L * (cr + 8), S.RED, 2, "arr")
    b += S.t(290, 282, "致死的トライアド ── 3つは互いを悪化させる", 16.5, S.RED, "middle",
             bold=True)
    items = [("止める", "外科的止血・IVR・ターニケット・圧迫。これが最優先", "red"),
             ("温める", "加温輸液・室温・強制対流式加温。34℃を切ると凝固は急速に悪化", "gold"),
             ("戻す", "赤血球・FFP・血小板を比率で。フィブリノゲンを切らさない", "blue"),
             ("直す", "iCa 1.1〜1.3 mmol/Lを実測。クエン酸負荷でCaは必ず下がる", "green"),
             ("測る", "体温・pH・乳酸・iCa・フィブリノゲンを繰り返し。1回では足りない", "gray")]
