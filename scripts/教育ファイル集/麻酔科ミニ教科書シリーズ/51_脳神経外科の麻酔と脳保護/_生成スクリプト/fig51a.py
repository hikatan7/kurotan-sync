def f01():
    cv = Canvas(W, 1300)
    y = head(cv, "図1-1　頭蓋の中身は三つ",
             "合計が一定なので、どれかが増えれば、ほかが減らなければならない。")
    h = cols(cv, W, y, (
        ("脳実質", "purple",
         ["腫瘍", "浮腫", "挫傷"]),
        ("血液", "red",
         ["動脈側の血流", "静脈のうっ滞", "血腫"]),
        ("脳脊髄液", "blue",
         ["産生と吸収", "水頭症", "── 逃げ場になる"]),
    ), mh=250, gap=28)
    y2 = y + h + 54
    h2 = band(cv, W, y2, [
        "代償が効いているあいだ、内容物が増えても圧はあまり上がらない ── ",
        "脳脊髄液が押し出され、静脈血が逃げるから。しかし余地を使い切ると、",
        "わずかな増加で圧が急に上がる。",
    ], title="代償には限りがある", ts=17)
    band(cv, W, y2 + h2 + 46, [
        "腹腔と同じ「途中までゆるく、あるところから急に硬くなる」性質 ── ",
        "ただし頭蓋のほうが、限界が早く来る。",
    ], style="amber", mh=150)
    cv.save(path("f01_skull.png"))


