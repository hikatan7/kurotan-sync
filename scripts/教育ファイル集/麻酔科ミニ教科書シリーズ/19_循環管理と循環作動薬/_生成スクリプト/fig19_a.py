def f03():
    W, H = 1520, 900
    cv = Canvas(W, H)
    ax = cv.ax
    cv.title(W / 2, 44, "動脈圧波形から読めること —— 数字の外にある情報",
             size=12.5, ha="center")
    L, R, T, B = 90, 900, 100, 420
    cv.rect(L, T, R - L, B - T, fc="#fbfcfd", ec="#c9d2dc", lw=1.4)
    t = np.linspace(0, 3, 900)
    base = 0.0
    wave = np.zeros_like(t)
    for k in range(3):
        s = t - k
        m = (s >= 0) & (s < 1)
        u = s[m]
        w = np.where(u < 0.18, np.sin(u / 0.18 * np.pi / 2) ** 0.8,
                     0.0)
        decay = np.exp(-(u - 0.18) * 3.2)
        w2 = np.where(u >= 0.18, decay * (1 + 0.16 * np.exp(
            -((u - 0.34) ** 2) / 0.0016)), 0.0)
        wave[m] = np.maximum(w, w2 * 0.98)
    yy = B - 30 - wave * (B - T - 70)
    xx = L + 20 + t / 3.0 * (R - L - 40)
    ax.plot(xx, yy, color=NAVY, lw=2.4, zorder=4)
    ann = [
        (0.10, "立ち上がりの傾き＝収縮性", RED, -60),
        (0.34, "重拍切痕＝大動脈弁閉鎖", GREEN, -110),
        (0.62, "下降脚の勾配＝血管抵抗", BLUE, -60),
        (0.86, "拍ごとの高さの差＝呼吸性変動", PURPLE, -110),
    ]
    # 波形には番号だけを置き、説明は右の凡例にまとめる（線と文字を重ねない）
    for k, (frac, lab, col, dy) in enumerate(ann):
        i = int(frac * len(t))
        top = max(yy[i] - 56, T + 30)
        cv.arrow((xx[i], top + 12), (xx[i], yy[i] - 6), color=col, lw=1.8,
                 head=9)
        cv.text(xx[i], top - 4, "①②③④"[k], size=12, color=col, weight="bold",
                z=6)
        ly = T + 40 + k * 72
        cv.text(R + 40, ly, "①②③④"[k], size=12, color=col, weight="bold",
                ha="left")
        cv.text(R + 80, ly, lab, size=10.4, color=col, weight="bold",
                ha="left")
    y = rows(cv, W, 470, [
        ("立ち上がりが鈍い", RED,
         ["収縮性の低下、あるいは大動脈弁狭窄。強心薬を考える手がかりになる"]),
        ("下降脚が急で拡張期圧が低い", BLUE,
         ["血管が開いている。血管収縮薬が効きやすい状態"]),
        ("拍ごとに高さが揺れる", PURPLE,
         ["陽圧換気に同期した変動なら、輸液に反応する可能性が高い（第5章）"]),
        ("波形がなまる・平坦になる", GREY,
         ["ライン系の問題（凝血、屈曲、気泡、位置）をまず疑う。"
          "数字を信じる前に波形を見る"]),
    ], name_sz=10.4, body_sz=10.2, lh=1.5)
    note(cv, W, y + 24,
         "※ 図は模式であり、実際の波形は測定部位で形が変わる。"
         "末梢ほど収縮期圧は高く、立ち上がりは鋭くなる。"
         "平均動脈圧は部位による差が小さいため、比較には平均を使う。")
    cv.save(P("f03_arterial_waveform.png"))


