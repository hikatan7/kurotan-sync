def f04():
    W, H = 1520, 920
    cv = Canvas(W, H)
    ax = cv.ax
    cv.title(W / 2, 44,
             "同じ輸液でも、どこにいるかで効果が違う",
             size=12.5, ha="center")
    L, R, T, B = 110, 800, 100, 450
    cv.rect(L, T, R - L, B - T, fc="#fbfcfd", ec="#c9d2dc", lw=1.4)
    x = np.linspace(0, 1, 200)
    for gain, col, lab in ((1.0, GREEN, "収縮性が保たれた心"),
                           (0.5, RED, "収縮性が落ちた心")):
        yy = B - 30 - (B - T - 70) * gain * (1 - np.exp(-x * 3.4))
        ax.plot(L + 20 + x * (R - L - 40), yy, color=col, lw=2.8, zorder=4)
        cv.text(R - 16, yy[-1] + (-22 if gain == 1.0 else 26), lab, size=10.0,
                color=col, ha="right")
    for frac, col, lab in ((0.16, BLUE, "ここでは効く"),
                           (0.78, AMBER, "ここでは効かない")):
        xi = L + 20 + frac * (R - L - 40)
        yi = B - 30 - (B - T - 70) * (1 - np.exp(-frac * 3.4))
        ax.add_patch(Circle((xi, yi), 9, facecolor=col, edgecolor="white",
                            lw=1.8, zorder=6))
        if frac < 0.5:
            cv.text(L + 16, T + 36, lab, size=10.2, color=col, weight="bold",
                    ha="left", z=7)
            cv.arrow((L + 70, T + 54), (xi - 4, yi - 12), color=col, lw=1.6,
                     head=8)
        else:
            cv.text(xi - 60, yi + 60, lab, size=10.2, color=col, weight="bold",
                    z=7)
    cv.text(L + 4, T - 18, "1回拍出量", size=10, color=GREY, ha="left")
    cv.text(R - 10, B + 24, "前負荷（心室の充満） →", size=10, color=GREY,
            ha="right")
    def _w(lines):
        out = []
        for ln in lines:
            out += cv.wrap(ln, W - 840 - 80 - 48, 10.4)
        return out
    h1 = textbox(cv, 840, 100, W - 840 - 80,
            _w(["曲線の立ち上がり部分にいるときだけ、"
             "輸液は1回拍出量を増やす。",
             "平坦部にいるときの輸液は、"
             "浮腫と静脈圧の上昇を作るだけになる。",
             "同じ患者でも、麻酔・出血・体位で"
             "位置は動く。",
             "だから「輸液するか」は毎回問い直す。"]),
            10.4, style="blue", title="輸液反応性とは、この曲線上の位置のこと",
            title_size=11.6, pad_x=24, pad_y=20)
    h2 = textbox(cv, 840, 100 + h1 + 20, W - 840 - 80,
            _w(["中心静脈圧は「今の充満圧」であり、",
             "曲線上の位置は教えてくれない。",
             "低い値は輸液の余地を示唆するが、",
             "高い値は「輸液が効かない」ことの証明にはならない。"]),
            10.4, style="amber", title="静的な圧では位置が分からない",
            title_size=11.6, pad_x=24, pad_y=20)
    note(cv, W, max(B + 70, 100 + h1 + 20 + h2 + 30),
         "※ 収縮性が落ちた心（下の曲線）では、"
         "同じだけ前負荷を増やしても1回拍出量の増え方が小さく、"
         "平坦部に達するのも早い。")
    cv.save(P("f04_starling.png"))


