def _two(cv, y, t1, s1, l1, t2, s2, l2, size=14, ts=17, mh=320):
    bw = (W - 112 - 40) / 2
    h1 = textbox(cv, 56, y, bw, l1, size, style=s1, title=t1,
                 title_size=ts, min_h=mh)
    h2 = textbox(cv, 56 + bw + 40, y, bw, l2, size, style=s2, title=t2,
                 title_size=ts, min_h=mh)
    return max(h1, h2)


def _cols(cv, y, cols, size=12.5, ts=14.5, mh=270, gap=22):
    bw = (W - 112 - (len(cols) - 1) * gap) / len(cols)
    hs = []
    for i, (ttl, st, lines) in enumerate(cols):
        hs.append(textbox(cv, 56 + i * (bw + gap), y, bw, lines, size,
                          style=st, title=ttl, title_size=ts, min_h=mh))
    return max(hs)


