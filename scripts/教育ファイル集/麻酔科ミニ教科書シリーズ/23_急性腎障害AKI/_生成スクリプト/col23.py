def apply(blocks):
    """指定した節の直後にコラムを差し込む。"""
    out, pending = [], None
    for b in blocks:
        if b[0] in ("h1", "h2", "h3") and pending:
            out.extend(COLUMNS[pending])
            pending = None
        # 節（h3）が無い章もあるので、章見出しでも受ける。
        # その場合は次の章の直前 ── つまり章の末尾に入る。
        if b[0] in ("h2", "h3"):
            for k in COLUMNS:
                if str(b[1]).startswith(k):
                    pending = k
                    break
        out.append(b)
    if pending:
        out.extend(COLUMNS[pending])
    return out
