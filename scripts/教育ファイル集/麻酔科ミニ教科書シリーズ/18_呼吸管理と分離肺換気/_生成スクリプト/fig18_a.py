def f06():
    W, H = 1520, 900
    cv = Canvas(W, H)
    ax = cv.ax
    cv.title(W / 2, 44, "グラフィックで最初に見る4つ —— 波形は数字より早く語る",
             size=12.5, ha="center")
    PANELS = [
        ("① 呼気フローが基線に戻らない", RED, "吐ききれていない（内因性呼気終末陽圧）",
         "呼気時間を延ばす／回数を減らす／気道抵抗を下げる"),
        ("② 呼気の立ち下がりが鈍い", AMBER, "気道抵抗の上昇",
         "分泌物・気管支攣縮・チューブの屈曲や狭窄を探す"),
        ("③ 吸気の途中でへこむ", BLUE, "患者の吸気努力（ファイティング）",
         "鎮痛・鎮静・トリガー感度・吸気流量の設定を見直す"),
        ("④ 吸気量と呼気量が合わない", PURPLE, "リーク",
         "カフ圧・回路接続、分離肺換気なら気管支カフを確認する"),
    ]
    L, R = 60, W - 60
    GAP = 20
    CW = (R - L - GAP * 3) / 4
    HH, PH = 52, 178
    for i, (head, col, diag, act) in enumerate(PANELS):
        x = L + i * (CW + GAP)
        cv.box(x, 92, CW, HH, fc=col, ec=col, lw=0, radius=7)
        sz = min(cv.fit_size([head], CW - 28, 11.0, weight="bold"), 11.0)
        cv.text(x + CW / 2, 92 + HH / 2, head, size=sz, color="white",
                weight="bold")
        cv.box(x, 92 + HH + 8, CW, PH, fc="#fbfcfd", ec=col, lw=1.6, radius=8)
        bx0, bx1 = x + 26, x + CW - 26
        base = 92 + HH + 8 + PH - 42
        tt = np.linspace(0, 1, 160)
        if i == 0:
            w = -np.exp(-tt * 2.0) * 52
            w[tt < 0.12] = 44
        elif i == 1:
            w = -np.exp(-tt * 1.1) * 52
            w[tt < 0.12] = 44
        elif i == 2:
            w = np.where(tt < 0.45,
                         44 - 38 * np.exp(-((tt - 0.28) ** 2) / 0.004),
                         -np.exp(-(tt - 0.45) * 5) * 52)
        else:
            w = np.where(tt < 0.4, 44, -np.exp(-(tt - 0.4) * 4) * 30)
        ax.plot([bx0, bx1], [base, base], color="#c9d2dc", lw=1.0, zorder=2)
        ax.plot(bx0 + tt * (bx1 - bx0), base - w, color=col, lw=2.2, zorder=4)
        cv.text(x + CW / 2, 92 + HH + 30, "フロー波形（模式）", size=9.2,
                color=GREY)
    y = 92 + HH + 8 + PH + 28
    y = rows(cv, W, y,
             [(("①", "②", "③", "④")[i] + "　" + p[2], p[1], [p[3]])
              for i, p in enumerate(PANELS)],
             name_sz=10.2, body_sz=10.2, lh=1.5)
    note(cv, W, y + 24,
         "※ 数値のアラームが鳴る前に、波形は形を変えている。"
         "分離肺換気では、この4つに「片肺分の量に見合った波形か」が加わる。")
    cv.save(P("f06_graphics.png"))


