def f04():
    W, H = 1520, 1080
    cv = Canvas(W, H)
    ax = cv.ax
    cv.title(W / 2, 44,
             "時定数 ＝ 気道抵抗 × コンプライアンス —— 3つ分で約95%が出入りする",
             size=12.5, ha="center")
    L, R, T, B = 100, 740, 130, 450
    cv.rect(L, T, R - L, B - T, fc="#fbfcfd", ec="#c9d2dc", lw=1.4)
    t = np.linspace(0, 5, 200)
    CURVES = ((1.0, BLUE, "標準"), (2.0, AMBER, "抵抗が2倍"),
              (0.5, GREEN, "コンプライアンス半分"))
    for tau, col, lab in CURVES:
        yy = B - (B - T - 34) * (1 - np.exp(-t / tau))
        ax.plot(L + 20 + t * (R - L - 40) / 5.0, yy, color=col, lw=2.6, zorder=4)
    for k in (1, 2, 3):
        x = L + 20 + k * (R - L - 40) / 5.0
        ax.plot([x, x], [T + 12, B], color="#c9d2dc", lw=1.0, ls=":", zorder=2)
        cv.text(x, B + 22, "%d τ" % k, size=9.8, color=GREY)
        # 割合は枠の上（曲線と重ならない位置）に出す
        cv.text(x, T - 16, ("63%", "86%", "95%")[k - 1], size=9.8,
                color=NAVY, weight="bold")
    cv.text(L, T - 50, "呼出された量", size=10, color=GREY, ha="left")
    cv.text(R - 10, B + 46, "時間 →", size=10, color=GREY, ha="right")
    # 凡例は枠の下に横並び
    for k, (tau, col, lab) in enumerate(CURVES):
        ly = B + 80 + k * 30
        ax.plot([L + 10, L + 50], [ly, ly], color=col, lw=3, zorder=4)
        cv.text(L + 60, ly, lab, size=10, color=col, ha="left")

    RX, RW = 800, W - 800 - 70

    def box(y, lines, title, style):
        wl = []
        for ln in lines:
            wl += cv.wrap(ln, RW - 48, 10.6)
        return textbox(cv, RX, y, RW, wl, 10.6, style=style, title=title,
                       title_size=11.8, pad_x=24, pad_y=18)

    h1 = box(100, ["気道抵抗が上がる（気管支攣縮、細いチューブ、分泌物）と、"
                   "呼出に時間がかかる。",
                   "呼気時間が時定数3つ分に足りないと、吐ききる前に次の吸気が始まる。",
                   "残った空気が積み上がる＝内因性呼気終末陽圧。",
                   "対処は「呼気時間を延ばす」。回数を減らす、吸気時間を短くする、"
                   "抵抗そのものを下げる。"],
             "時定数が伸びるとどうなるか", "amber")
    h2 = box(100 + h1 + 24,
             ["肺が硬いと時定数は短くなる。",
              "急性呼吸窮迫症候群のような硬い肺では、呼気が短くても吐ききれる。",
              "積み上がりが問題になるのは主に閉塞性の病態である。"],
             "硬い肺では逆に短くなる", "blue")
    note(cv, W, max(B + 180, 100 + h1 + 24 + h2 + 30),
         "※ 「呼気フロー波形が基線に戻る前に次の吸気が始まっていないか」を"
         "毎回見る習慣が、内因性呼気終末陽圧を最も早く見つける。")
    cv.save(P("f04_time_constant.png"))


