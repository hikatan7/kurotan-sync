def f01():
    cv = Canvas(W, 1300)
    y = head(cv, "図3-1　弁膜症を二つの軸で読む",
             "病名ではなく、どちらの心室にどの負荷がかかっているかで管理が決まる。")
    h = two(cv, W, y,
            "圧負荷", "red",
            ["大動脈弁狭窄（左室）", "僧帽弁狭窄（左房と肺循環）",
             "求心性の肥大／拡張が悪い",
             "── 充満する時間と圧が命"],
            "容量負荷", "blue",
            ["大動脈弁閉鎖不全（左室）", "僧帽弁閉鎖不全（左室と左房）",
             "三尖弁閉鎖不全（右室）", "遠心性の拡大",
             "── 前へ出しやすくする"],
            mh=310)
    y2 = y + h + 54
    h2 = band(cv, W, y2, [
        "「脈は速めに／遅めに」「後負荷は下げる／保つ」という指示は、",
        "すべてこの二軸から出ている。覚えるのは病名ではなく、負荷の向きである。",
    ], title="この図の要点", ts=17)
    band(cv, W, y2 + h2 + 46, [
        "弁膜症手術では、手術そのものが患者の生理を変える ── ",
        "狭窄を取れば後負荷が急に減り、逆流を止めれば前負荷が急に減る（第16章）。",
    ], style="amber", mh=150)
    cv.save(path("f01_two_axes.png"))


