def f02():
    cv = Canvas(W, 1700)
    y = head(cv, "図4-1　内径が半分になると、断面積は 4 分の 1",
             "気管を円とみなすと、断面積は内径の 2 乗に比例する。CT の「径で 50%」と「面積で 50%」は別物。")
    ratios = (1.0, 0.7, 0.5, 0.3)
    cx0, gap = 270, 420
    R = 150
    for i, r in enumerate(ratios):
        cx = cx0 + i * gap
        cy = y + 190
        from matplotlib.patches import Circle
        cv.ax.add_patch(Circle((cx, cy), R, facecolor="#f2f4f6", edgecolor="#8d97a3",
                               lw=2, zorder=2))
        cv.ax.add_patch(Circle((cx, cy), R * r, facecolor="#eaf1f8" if r > 0.5 else "#fceeec",
                               edgecolor=BLUE if r > 0.5 else RED, lw=2.6, zorder=3))
        cv.text(cx, cy + R + 52, "内径 %d%%" % round(r * 100), size=17, weight="bold", color=INK)
        cv.text(cx, cy + R + 100, "断面積 %d%%" % round(r * r * 100), size=17,
                weight="bold", color=BLUE if r > 0.5 else RED)
    y2 = y + 190 + R + 160
    h2 = band(cv, W, y2, [
        "成人の研究で術後の呼吸器合併症と結びついたのは「気管の圧迫 50% 超」（CT）",
        "小児の分類では「断面積 70% 超の減少」が高リスクに入る。",
        "数字は一本の線ではない ── 症状・体位による変化・血管の圧迫と重ねて読む。",
    ], title="閾値の読み方", ts=17)
    _save(cv, "f02_area.png")


