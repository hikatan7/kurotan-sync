def write_csv(path, data):
    """列名→値リストの dict を CSV に書く。pandas の有無を問わない。"""
    if pd is not None:
        pd.DataFrame(data).to_csv(path, index=False, encoding="utf-8-sig")
        return
    cols = list(data.keys())
    with _io.open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for row in zip(*[data[c] for c in cols]):
            w.writerow(row)

