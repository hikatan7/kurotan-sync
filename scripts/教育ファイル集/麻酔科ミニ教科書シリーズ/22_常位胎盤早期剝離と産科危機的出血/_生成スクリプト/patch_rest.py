import io


def ed(path, pairs):
    s = io.open(path, encoding="utf-8").read()
    for a, b in pairs:
        assert a in s, (path, a[:70])
        s = s.replace(a, b, 1)
    io.open(path, "w", encoding="utf-8").write(s)
    print("patched", path)


