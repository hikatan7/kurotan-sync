def main():
    copy_figs()
    doc = docx.Document(DOCX)
    body = doc.element.body
    n_before = len(body)
    add_appendix(doc)
    new = list(body)[n_before - 1:]          # sectPr の手前に挿入されている
    new = [e for e in new if e.tag.split("}")[1] != "sectPr"]

    # 「おわりに」の段落を探して、その前へ移す
    target = None
    for p in doc.paragraphs:
        if p.text.strip() == "おわりに" and p.style.name.startswith("Heading"):
            target = p._p
            break
    if target is None:
        raise SystemExit("『おわりに』が見つからない")
