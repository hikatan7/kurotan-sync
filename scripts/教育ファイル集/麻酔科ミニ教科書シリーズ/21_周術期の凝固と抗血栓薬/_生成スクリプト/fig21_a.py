def P(n):
    return os.path.join(OUT, n)


def steps(cv, W, TOP, data, RH=96, GAP=13, L=64, NUMW=70,
          num_sz=18, name_sz=12.2, body_sz=10.4):
    R = W - L
    for i, (num, name, col, lines) in enumerate(data):
        y0 = TOP + i * (RH + GAP)
        cv.box(L, y0, R - L, RH, fc="white", ec=col, lw=1.8, radius=8)
        cv.box(L, y0, NUMW, RH, fc=col, ec=col, lw=0, radius=8)
        cv.text(L + NUMW / 2, y0 + RH / 2, num, size=num_sz, color="white",
                weight="bold")
        cv.text(L + NUMW + 28, y0 + RH / 2 - 16, name, size=name_sz,
                color=col, weight="bold", ha="left")
        for j, ln in enumerate(lines):
            cv.text(L + NUMW + 28, y0 + RH / 2 + 16 + 22 * j, ln,
                    size=body_sz, color=INK, ha="left")
    return TOP + len(data) * (RH + GAP) - GAP


