def f17():
    W, H = 1520, 700
    cv = Canvas(W, H)
    ax = cv.ax
    cv.title(W / 2, 44, "腰椎の超音波 —— どの当て方で、何が見えるか",
             size=12.5, ha="center")
    PANELS = [
        ("傍正中矢状斜走査", "#2e6da4",
         ["正中から 2〜3 cm 外側、椎弓の上に置く",
          "やや内側へ傾け、脊柱管の最も広い部分へ音を入れる",
          "椎弓が「馬の頭」のように並んで見える",
          "黄色靱帯と後部硬膜のあいだの低信号域が硬膜外腔"]),
        ("横断（棘突起間）走査", "#b8760f",
         ["腰椎では比較的とりやすい",
          "黄色靱帯は見えにくい（椎弓への付着による異方性のため）",
          "硬膜外腔も、傍正中矢状斜走査より見えにくい",
          "胸椎中位（T4〜8）では棘突起が急峻に下向きで、とりにくい"]),
    ]
    L, GAPX = 64, 44
    PW = (W - L * 2 - GAPX) / 2.0
    PTOP, HH = 90, 54
    BTOP = PTOP + HH + 8
    sz = min(cv.fit_size(["・" + l for p in PANELS for l in p[2]],
                         PW - 56, 10.0), 10.0)
    nl = max(sum(len(cv.wrap(l, PW - 62, sz)) for l in p[2]) for p in PANELS)
    BH = 30 + LH(sz, 1.8) * (nl - 1) + LH(sz, 1.0) * 0.5 + 22
    for i, (head, col, lines) in enumerate(PANELS):
        px = L + i * (PW + GAPX)
        cv.box(px, PTOP, PW, HH, fc=col, ec=col, lw=0, radius=7)
        cv.text(px + PW / 2, PTOP + HH / 2, head, size=12, color="white",
                weight="bold")
        cv.box(px, BTOP, PW, BH, fc="white", ec=col, lw=1.8, radius=8)
        k = 0
        for ln in lines:
            for j, sub in enumerate(cv.wrap(ln, PW - 62, sz)):
                cv.text(px + 26, BTOP + 30 + LH(sz, 1.8) * k,
                        ("・" if j == 0 else "　") + sub, size=sz, color=INK,
                        ha="left")
                k += 1
    # 見え方の模式（椎弓の並び）
    IY = BTOP + BH + 26
    IH = 150
    cv.box(L, IY, W - L * 2, IH, fc="white", ec="#9aa4b0", lw=1.6, radius=8)
    ux, uy, uw, uh = L + 30, IY + 22, W - L * 2 - 60, IH - 44
    ax.add_patch(Rectangle((ux, uy), uw, uh, facecolor="#2b2f36",
                           edgecolor="none", zorder=3))
    for k in range(5):
        bx = ux + 70 + k * (uw - 160) / 4.0
        ax.add_patch(Polygon([[bx - 34, uy + 74], [bx - 12, uy + 40],
                              [bx + 22, uy + 40], [bx + 40, uy + 74]],
                             closed=True, facecolor="#e8e2d6",
                             edgecolor="none", zorder=5))
        ax.plot([bx + 44, bx + 62], [uy + 74, uy + 74], color="#8fd0c0",
                lw=2.4, zorder=5)
    cv.text(ux + 24, uy + 24, "椎弓（「馬の頭」）", size=9.4, color="#e8e2d6",
            ha="left", z=6)
    cv.text(ux + uw - 24, uy + uh - 18,
            "椎弓のあいだの窓 ── ここから脊柱管が見える", size=9.4,
            color="#8fd0c0", ha="right", z=6)
    note(cv, W, IY + IH + 30,
         "※ 模式図である。関節突起は「ラクダのこぶ」のように見えると表現される。"
         "腰仙骨接合部（L5-S1）は椎弓間の窓が最も広い。")
    cv.save(P("f17_lumbar_us.png"))


