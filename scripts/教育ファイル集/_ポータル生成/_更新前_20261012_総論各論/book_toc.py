def classify(path, title):
    """資料名＋フォルダから (部, 章) を返す。どれにも当たらなければ (None, "")。"""
    s = (title + u" " + path).lower()
    for keys, part, chap in RULES:
        if any(k in s for k in keys):
            return part, chap
    return None, u""


