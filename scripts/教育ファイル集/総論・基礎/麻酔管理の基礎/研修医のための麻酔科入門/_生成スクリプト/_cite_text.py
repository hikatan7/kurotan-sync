"""出典で裏付けられない数字を直す（2026-10-08）。"""
import io


def edit(p, pairs):
    s = io.open(p, encoding="utf-8").read()
    for a, b in pairs:
        assert a in s, (p, a)
        s = s.replace(a, b, 1)
    io.open(p, "w", encoding="utf-8").write(s)
    print(p, "ok")


