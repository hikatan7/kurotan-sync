import io, re


def edit(p, pairs):
    s = io.open(p, encoding="utf-8").read()
    for a, b in pairs:
        if a not in s:
            raise SystemExit("NOT FOUND in %s: %s" % (p, a[:60]))
        s = s.replace(a, b, 1)
    io.open(p, "w", encoding="utf-8").write(s)
    print(p, "ok", len(pairs))


def block(p, start, end_marker):
    """start で始まる box(...) を、次の end_marker の直前までまるごと返す"""
    s = io.open(p, encoding="utf-8").read()
    i = s.index(start)
    j = s.index(end_marker, i)
    return s[i:j]


