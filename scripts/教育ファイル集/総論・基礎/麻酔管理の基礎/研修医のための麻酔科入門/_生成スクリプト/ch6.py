# ── 図：糸球体の圧バランス ────────────────────────
def figgfr():
    b = ""
    b += S.t(0, 16, "糸球体の圧バランス ── 正味濾過圧はわずか10 mmHg", 18, S.NAVY, bold=True)
    bars = [("糸球体毛細血管圧 P_GC", +55, "red"),
            ("Bowman嚢内圧 P_BS", -15, "gray"),
            ("血漿膠質浸透圧 COP", -30, "blue")]
    y, x0, sc = 34, 340, 5.4
    for name, v, tone in bars:
        b += S.t(0, y + 22, name, 16, S.INK)
        if v > 0:
            b += S.rect(x0, y, v * sc, 30, tone, r=3)
            b += S.t(x0 + v * sc + 10, y + 22, f"＋{v}", 16, S.TXT[tone], bold=True)
        else:
            b += S.rect(x0 + v * sc, y, -v * sc, 30, tone, r=3)
            b += S.t(x0 + v * sc - 10, y + 22, f"−{-v}", 16, S.TXT[tone], "end", bold=True)
        y += 40
    b += S.line(x0, 28, x0, y + 4, S.SUB, 1.4)
    b += S.rect(0, y + 10, 1000, 40, "gold", r=5)
    b += S.t(14, y + 36, "正味濾過圧 ＝ ＋55 − 15 − 30 ＝ ＋10 mmHg　── この10 mmHgしか余裕がない。",
             17, S.TXT["gold"], bold=True)
    y += 62
    risks = ["MAPが20 mmHg下がれば止まる", "尿管閉塞でP_BSが10上がれば止まる",
             "静脈うっ血（CVP↑）で下流圧が上がれば止まる", "膠質浸透圧が上がっても濾過は減る"]
    for i, r in enumerate(risks):
        b += S.rect((i % 2) * 510, y + (i // 2) * 40, 490, 32, "red", r=4)
        b += S.t((i % 2) * 510 + 12, y + (i // 2) * 40 + 22, "・" + r, 15.5, S.TXT["red"])
