from calc import *  # noqa: F401,F403


def _sign(x):
    return "＋" if x >= 0 else "−"


def _stage(op, inv, fin):
    s = (_sign(op), _sign(inv), _sign(fin))
    return {("−", "−", "＋"): "導入期", ("＋", "−", "＋"): "成長期", ("＋", "−", "−"): "成熟期",
            ("−", "＋", "＋"): "衰退期", ("−", "＋", "−"): "衰退期"}.get(s, "淘汰期")


